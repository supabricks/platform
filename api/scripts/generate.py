#!/usr/bin/env python3
"""Generate the server's route table and the README status table from the spec.

The specification is the source of truth for routes. This reads
api/openapi.yaml and api/status.yaml and writes:

  crates/local/src/rest/routes.rs   every operation that is implemented or
                                    complete, as an enum and a route table
  api/README.md                     the status table between its markers

With --check it writes nothing and fails if either file is out of date, if an
operation has no stage, or if status.yaml names something the spec lacks.
"""
import pathlib, re, sys
import yaml

API = pathlib.Path(__file__).resolve().parent.parent
REPO = API.parent
ROUTES = REPO / 'crates/local/src/rest/routes.rs'
README = API / 'README.md'
METHODS = ('get', 'post', 'put', 'patch', 'delete')
STAGES = ('draft', 'frozen', 'implemented', 'complete', 'deferred')
SERVED = ('implemented', 'complete')


def operations():
    """Every operation in the spec: (path, method, operationId, domain)."""
    root = yaml.safe_load((API / 'openapi.yaml').read_text())
    files, found = {}, []
    for path, item in root['paths'].items():
        file, _, key = item['$ref'].partition('#/')
        target = (API / file).resolve()
        doc = files.setdefault(target, yaml.safe_load(target.read_text()))
        for method in METHODS:
            if method in doc[key]:
                found.append((path, method, doc[key][method]['operationId'], target.parent.name))
    return found


def stages(ops):
    status = yaml.safe_load((API / 'status.yaml').read_text())
    domains, overrides = status['domains'], status.get('operations') or {}
    errors, result = [], {}
    for name in overrides:
        if name not in {o[2] for o in ops}:
            errors.append(f'status.yaml names operation {name}, which the spec does not define')
    for name in domains:
        if name not in {o[3] for o in ops}:
            errors.append(f'status.yaml names domain {name}, which has no operations')
    for _, _, name, domain in ops:
        if domain not in domains:
            errors.append(f'domain {domain} has no entry in status.yaml')
            continue
        stage = (overrides.get(name) or domains[domain])['stage']
        if stage not in STAGES:
            errors.append(f'{name}: unknown stage {stage}')
        if stage == 'deferred' and not (overrides.get(name) or {}).get('issue'):
            errors.append(f'{name}: a deferred operation needs an issue')
        result[name] = stage
    return domains, result, errors


def variant(operation_id):
    return operation_id[0].upper() + operation_id[1:]


def routes_rs(ops, stage):
    served = sorted((o for o in ops if stage.get(o[2]) in SERVED), key=lambda o: (o[0], o[1]))
    lines = [
        '// Generated by api/scripts/generate.py from api/openapi.yaml and api/status.yaml.',
        '// Do not edit. Change the specification or the status file and regenerate.',
        '',
        '/// Every operation the server routes. Adding one here without a handler',
        '/// does not compile, because the dispatcher matches on it exhaustively.',
        '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
        'pub enum Operation {',
        *[f'    {variant(o[2])},' for o in sorted(served, key=lambda o: o[2])],
        '}',
        '',
        '/// Method, path template and operation, with `{name}` for a path parameter.',
        '#[rustfmt::skip]',
        'pub const ROUTES: &[(&str, &str, Operation)] = &[',
        *[f'    ("{o[1].upper()}", "{o[0]}", Operation::{variant(o[2])}),' for o in served],
        '];',
        '',
    ]
    return '\n'.join(lines)


def readme_table(ops, domains, stage):
    rows = ['| Domain | Slice | Stage | Operations | Served | Deferred |', '|---|---|---|---|---|---|']
    for name, info in domains.items():
        mine = [o[2] for o in ops if o[3] == name]
        rows.append(f"| `{name}` | {info['slice']} | {info['stage']} | {len(mine)} | "
                    f"{sum(stage[m] in SERVED for m in mine)} | {sum(stage[m] == 'deferred' for m in mine)} |")
    return '\n'.join(rows)


def main():
    check = '--check' in sys.argv
    ops = operations()
    domains, stage, errors = stages(ops)
    names = [o[2] for o in ops]
    errors += [f'operationId {n} is used more than once' for n in sorted({n for n in names if names.count(n) > 1})]
    if errors:
        sys.exit('\n'.join(errors))
    readme = README.read_text()
    block = re.compile(r'(<!-- status:start -->\n).*?(<!-- status:end -->)', re.S)
    if not block.search(readme):
        sys.exit('api/README.md has no status markers')
    wanted = {ROUTES: routes_rs(ops, stage),
              README: block.sub(lambda m: m.group(1) + readme_table(ops, domains, stage) + '\n' + m.group(2), readme)}
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
    if check:
        if stale:
            sys.exit('out of date, run python3 api/scripts/generate.py: ' + ', '.join(str(p.relative_to(REPO)) for p in stale))
        print(f'{len(ops)} operations, {sum(s in SERVED for s in stage.values())} served; generated files are current')
        return
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p])
        print('wrote', p.relative_to(REPO))


if __name__ == '__main__':
    main()
